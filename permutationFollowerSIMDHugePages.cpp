#pragma GCC target("avx512f")
#pragma GCC optimize("O3")
#include<x86intrin.h>


#include<iostream>
#include<cstdint>
#include<chrono>
#include<unistd.h> //linux/UNIX specific
//#include<perfcpp/event_counter.hpp>
#include<sys/mman.h> //linux/UNIX specific
#include<linux/mman.h> //needed since glibc version < 2.40 doesn't define MAP_HUGE_1GB
#include<errno.h> //linux/UNIX specific
#include<err.h> //linux/UNIX specific
#include<string.h>

int main(int argc, char* argv[]) {
    uint64_t iterations;
    char* t = nullptr;
    if (argc != 2 || (iterations = strtoull(argv[1], &t, 10)) == 0 || errno) {
        std::cerr << "Reads from stdin a permutation with one cycle generated by permutationGeneratorConcurrent.\n"
            << "Exactly one parameter must be passed, iter: a nonnegative nonzero integer.\n"
            << "'Follows' the permutation iter times per concurrency level. Time to follow the permutation is recorded.\n"
            << "For each cycle, a line is printed with two tab separated values. First total time, second average time per follow operation.\n";
        return 1;
    }

    using clk = std::chrono::high_resolution_clock;
    using dur = std::chrono::duration<double>;
    auto beg = clk::now(), end = clk::now();

    const uint64_t cacheLineSize = sysconf(_SC_LEVEL1_DCACHE_LINESIZE); //linux/UNIX specific
    const uint64_t bytesPerPointer = sizeof(void*);
    const uint64_t bytesPerInt = sizeof(uint64_t);
    std::cerr << "Cache Line Size: " << cacheLineSize << std::endl;
    std::cerr << "Page Size: " << (1 << 30) << std::endl;
    std::cerr << "Size of void*: " << bytesPerPointer << std::endl;
    std::cerr << "Size of uint64_t: " << bytesPerInt << std::endl;

    if (bytesPerPointer < bytesPerInt) {
        std::cerr << "Invalidated assumption that pointer uses less bytes than uint64_t. Exiting!" << std::endl;
        return 1;
    }
    if (bytesPerPointer > cacheLineSize ) {
        std::cerr << "Invalidated assumption that pointer fits within one cache line. Exiting!" << std::endl;
        return 1;
    }
    if (bytesPerInt > cacheLineSize) {
        std::cerr << "Invalidated assumption that uint64_t fits within one cache line. Exiting!" << std::endl;
        return 1;
    }
    if (cacheLineSize % bytesPerPointer ) {
        std::cerr << "Invalidated assumption that pointer aligns to cache line. Exiting!" << std::endl;
        return 1;
    }
    if (cacheLineSize % bytesPerInt) {
        std::cerr << "Invalidated assumption that uint64_t aligns to cache line. Exiting!" << std::endl;
        return 1;
    }

    uint64_t intsPerLine = cacheLineSize/bytesPerInt;
    std::cerr << "uint64_t per cache line: " << intsPerLine << std::endl;

    uint64_t pointersPerLine = cacheLineSize/bytesPerPointer;
    std::cerr << "void* per cache line: " << pointersPerLine << std::endl;



    //get array
    uint64_t elements = 0, arrIntSize;
    std::cin.read(reinterpret_cast<char*>(&elements), bytesPerInt);
    arrIntSize = elements*intsPerLine;

    if (elements < intsPerLine) 
        return 1;

    beg = clk::now();
    //uint64_t *arrInt = new uint64_t[arrIntSize];
    uint64_t *arrInt = reinterpret_cast<uint64_t*>(mmap(NULL, arrIntSize*bytesPerInt, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_HUGETLB | MAP_HUGE_1GB, -1, 0));
    if (arrInt == MAP_FAILED) {
        perror("mmap");
        std::cerr << "mmap failed! Error: " << strerror(errno) << " (Code: " << errno << ")\n";
        err(EXIT_FAILURE, "mmap");
    }
    end = clk::now();
    std::cerr << "Allocating array of size " << arrIntSize*bytesPerInt << " bytes (aka " << elements << " cache lines) took " << dur(end - beg).count() << " seconds" << std::endl;
    beg = clk::now();
    std::cin.read(reinterpret_cast<char*>(arrInt), bytesPerInt*elements);
    end = clk::now();
    std::cerr << "Reading array of size " << arrIntSize << " bytes took " << dur(end - beg).count() << " seconds" << std::endl;

    uint64_t maxConcurrency = 0, concArrSize;
    std::cin.read(reinterpret_cast<char*>(&maxConcurrency), bytesPerInt);
    concArrSize = ((maxConcurrency*maxConcurrency+maxConcurrency)/2) - 1;

    std::cerr << "maxConcurrency: " << maxConcurrency << std::endl;
    std::cerr << "concArrSize: " << concArrSize << std::endl;

    beg = clk::now();
    uint64_t *checkpoints = new uint64_t[concArrSize];
    end = clk::now();
    std::cerr << "Allocating array of size " << concArrSize*bytesPerInt << " bytes took " << dur(end - beg).count() << " seconds" << std::endl;
    beg = clk::now();
    std::cin.read(reinterpret_cast<char*>(checkpoints), bytesPerInt*concArrSize);
    end = clk::now();

    //convert to one int per cache line array
    beg = clk::now();
    uint64_t orig = elements;
    for (uint64_t i = elements*intsPerLine; i -= intsPerLine;) {
        arrInt[i] = arrInt[--orig]*intsPerLine;
        arrInt[orig] = arrIntSize+orig;
    }
    arrInt[0] *= intsPerLine;

    //void***check = reinterpret_cast<void***>(checkpoints);
    if (intsPerLine != 8 || cacheLineSize != 64) {
        std::cerr << "Cache must be 64 bytes and uint64_t must take 8 bytes!" << std::endl;
        return 1;
    }
    __m512i* check = new __m512i[maxConcurrency/intsPerLine];
    //for (uint64_t i = 0; i < concArrSize; ++i)
        //check[i] = arr + (checkpoints[i] * pointersPerLine);
    for (uint64_t i = 0; i < concArrSize; ++i)
        checkpoints[i] *= intsPerLine;

    end = clk::now();
    std::cerr << "Converting to spaced int array took " << dur(end - beg).count() << " seconds" << std::endl;

    uint64_t jumps;
    /*
    //verify
    beg = clk::now();
    double temp;
    uint64_t ind = 0, jumps = 0;
    void** p = arr;
    do {
        p = reinterpret_cast<void**>(*p);
        ++jumps;
    } while (p != arr && jumps <= elements);
    end = clk::now();
    if (jumps != elements) {
        std::cerr << "Read permutation is not a cycle of length " << elements << "!\n";
        return 1;
    }
    std::cerr << "Verifying read permutation is a cycle of length one took " << (temp = dur(end - beg).count()) << " seconds."
       << " Average jump of " << (temp/elements)*1e9 << " nanoseconds.\n";
    */

    //test
    double* times = new double[iterations];

    jumps = std::max(elements, static_cast<uint64_t>(1) << 20);
    jumps = std::min(jumps, static_cast<uint64_t>(1) << 25);

    //auto config = perf::Config{};
    //config.include_kernel(false);       /// Disable kernel event recording.
    //config.include_hypervisor(false);   /// Disable hypervisor event recording.

    //std::vector<perf::CounterResult> counts(iterations);
    //void** p = arr;
    for (uint64_t conc = 2; conc <= maxConcurrency; ++conc) {
        if (conc % pointersPerLine == 0) {
            std::cout << elements*cacheLineSize << '\t' << elements << '\t' << jumps << '\t' << conc;
            uint64_t curJumps = jumps/conc + (jumps % conc != 0);
            uint64_t checkSize = conc/8;
            for (uint64_t i = 0; i < checkSize; ++i)
                check[i] = _mm512_set_epi64(checkpoints[i*8+7], checkpoints[i*8+6], checkpoints[i*8+5], checkpoints[i*8+4], 
                        checkpoints[i*8+3], checkpoints[i*8+2], checkpoints[i*8+1], checkpoints[i*8]);
            for (uint64_t i = 0; i < iterations; ++i) {
                beg = clk::now();
                for (uint64_t j = 0; j < curJumps; ++j) {
                    for (uint64_t k = 0; k < checkSize; ++k) {
                        check[k] = _mm512_i64gather_epi64(check[k], arrInt, 8);
                        //check[k] = reinterpret_cast<void**>(*(check[k]));
                    }
                }
                end = clk::now();
                times[i] = dur(end - beg).count();
                std::cout << '\t' << (times[i]/(curJumps*conc))*1e9;
                times[i] = _mm512_reduce_add_epi64(check[0])/intsPerLine;
                for (uint64_t k = 1; k < checkSize; ++k)
                    times[i] += _mm512_reduce_add_epi64(check[k])/intsPerLine;
            }
            std::cout << '\n';
        }
        checkpoints += conc;
    }
    //for (const auto [event_name, value] : counts[0]) {
    //    std::cout << event_name << "\t|\t:";
    //    for (uint64_t i = 0; i < iterations; ++i)
    //        std::cout << '\t' << counts[i][event_name].value() / jumps;
    //    std::cout << '\n';
    //}

    //output results
    for (uint64_t i = 0; i < iterations; ++i)
        std::cerr << times[i] << '\t';
    std::cerr << '\n';

    return 0;
}
